QString PixelFont::sanitize(const QString& text) {
    // 빠른 길: 바꿀 게 없으면 그대로 돌려준다
    bool need = false;
    for (const QChar ch : text) {
        const ushort u = ch.unicode();
        if (ch.isSurrogate() || u == 0xFE0F || u == 0x2714 || u == 0x2713 || u == 0x2705 || u == 0x2716 ||
            u == 0x274C || u == 0x23F8 || u == 0x27F3) { need = true; break; }
    }
    if (!need) return text;

    QString out;
    out.reserve(text.size());
    for (int i = 0; i < text.size(); ++i) {
        const QChar ch = text.at(i);
        const ushort u = ch.unicode();
        if (u == 0xFE0F) continue;                                  // 이모지 변형 선택자: 그리지 않는다
        if (ch.isHighSurrogate() && i + 1 < text.size() && text.at(i + 1).isLowSurrogate()) {
            const uint cp = QChar::surrogateToUcs4(ch, text.at(i + 1));
            ++i;
            QChar sub;
            switch (cp) {
            case 0x1F310:                     sub = QChar(0x25CE); break;   // 🌐 ◎
            case 0x1F534:                     sub = QChar(0x25CF); break;   // 🔴 ●
            case 0x1F512:                     sub = QChar(0x25A0); break;   // 🔒 ■
            case 0x1F513:                     sub = QChar(0x25A1); break;   // 🔓 □
            case 0x1F4A4:                     sub = QChar(0x25C7); break;   // 💤 ◇
            case 0x1F4BE: case 0x1F4C1: case 0x1F4C2:
            case 0x1F3AC: case 0x1F4F7: case 0x1F5BC:
                                              sub = QChar(0x25A3); break;   // 💾 📁 📂 🎬 📷 🖼 ▣
            case 0x1F504:                     sub = QChar(0x21BB); break;   // 🔄 ↻
            default:                          sub = QChar(0x25C6); break;   // 🎮 🎫 🔧 🧩 🎚 그 밖의 이모지 ◆
            }
            out += sub;
            continue;
        }
        switch (u) {
        case 0x2714: case 0x2713: case 0x2705: out += QChar(0x221A); break;   // ✔ ✓ ✅ √
        case 0x2716: case 0x274C:              out += QChar(0x00D7); break;   // ✖ ❌ ×
        case 0x23F8:                           out += QChar(0x2016); break;   // ⏸ ‖
        case 0x27F3:                           out += QChar(0x21BB); break;   // ⟳ ↻
        default:                               out += ch; break;
        }
    }
    return out;
}

const PixelFont::KoRun& PixelFont::koreanRun(const QString& run, const QColor& color, int px) {
    const QString key = run + QLatin1Char('\x1f') + QString::number(color.rgb(), 16)
                      + QLatin1Char('\x1f') + QString::number(px);
    auto it = m_ko.find(key);
    if (it != m_ko.end()) return it.value();

    const bool bundled = !bundledFamily().isEmpty();
    // 내장 폰트는 14px 로만 그리고 정수 배로 키운다(도트가 뭉개지지 않는다). px 는 원하는 크기.
    const int zoom = bundled ? qMax(1, px / BUNDLED_PX) : 1;
    QFont f;
    if (bundled) {
        f.setFamily(bundledFamily());
        f.setPixelSize(BUNDLED_PX);
        f.setStyleStrategy(QFont::NoAntialias);
        f.setHintingPreference(QFont::PreferFullHinting);
    } else {
        if (!koreanFamily().isEmpty()) f.setFamily(koreanFamily());
        f.setPixelSize(px);
        f.setStyleStrategy(QFont::StyleStrategy(QFont::PreferAntialias | QFont::NoSubpixelAntialias));
        f.setHintingPreference(QFont::PreferFullHinting);  // 획을 픽셀 격자에 붙여 또렷하게
    }
    f.setBold(false);                                  // 굵게 하면 한글 획이 붙어버린다

    const QFontMetrics fm(f);
    KoRun r;
    r.advance = fm.horizontalAdvance(run);
    const int pad = 2;
    const int w = qMax(1, r.advance + 2 * pad);
    const int hgt = qMax(1, fm.height() + 2 * pad);
    QImage img(w, hgt, QImage::Format_ARGB32_Premultiplied);
    img.fill(Qt::transparent);
    {
        QPainter q(&img);
        q.setFont(f);
        q.setPen(color);
        q.drawText(pad, pad + fm.ascent(), run);
    }
    // 굵게: 획 오른쪽에 점 1개를 더한다. 단, 오른쪽 두 칸이 모두 비어 있을 때만 더해서
    //   획 사이의 1점 틈이 메워지지 않는다 (통째로 겹쳐 그리면 래, 새 같은 글자가 뭉개진다).
    //   8x8 영문 글자와 비슷한 굵기가 된다. 확대(zoom)는 이 뒤에 하므로 배율과 상관없이 같은 모양이다.
    if (bundled) {
        const QImage src = img.copy();
        const QRgb ink = qPremultiply(qRgba(color.red(), color.green(), color.blue(), 255));
        for (int y = 0; y < src.height(); ++y) {
            const QRgb* in = reinterpret_cast<const QRgb*>(src.constScanLine(y));
            QRgb* out = reinterpret_cast<QRgb*>(img.scanLine(y));
            for (int x = 0; x + 2 < src.width(); ++x)
                if (qAlpha(in[x]) > 127 && qAlpha(in[x + 1]) <= 127 && qAlpha(in[x + 2]) <= 127)
                    out[x + 1] = ink;
        }
    }
    // 획을 살짝 진하게: 도트 글자처럼 알파를 밀어 올려 흐릿한 가장자리를 줄인다
    for (int y = 0; !bundled && y < img.height(); ++y) {
        QRgb* line = reinterpret_cast<QRgb*>(img.scanLine(y));
        for (int x = 0; x < img.width(); ++x) {
            const QRgb v = line[x];
            const int a = qAlpha(v);
            if (a == 0 || a == 255) continue;
            const int na = qMin(255, a * 3 / 2);
            line[x] = qPremultiply(qRgba(color.red(), color.green(), color.blue(), na));
        }
    }
    // 한글의 "몸통" 가운데가 셀 세로 중앙에 오도록 기준선 위치를 잰다
    const QRect body = fm.tightBoundingRect(QStringLiteral("한글"));
    r.baselineY = pad + fm.ascent() + (body.top() + body.height() / 2);    // 이미지 안에서 몸통 중앙의 y
    if (zoom > 1) {
        img = img.scaled(img.width() * zoom, img.height() * zoom, Qt::IgnoreAspectRatio, Qt::FastTransformation);
        r.advance *= zoom;
        r.baselineY *= zoom;
    }
    r.pad = pad * zoom;
    r.img = img;
    return m_ko.insert(key, r).value();
}

// ─────────────────────────────────────────────────────────────
const QImage& PixelFont::atlas(const QColor& color) {
    const QRgb key = color.rgb();
    auto it = m_atlas.find(key);
    if (it != m_atlas.end()) return it.value();

    // 0x20~0x7F 96칸 + © 1칸
    QImage img((COUNT + 1) * CELL_W, CELL_H, QImage::Format_ARGB32_Premultiplied);
    img.fill(Qt::transparent);

    const QRgb on = qPremultiply(qRgba(color.red(), color.green(), color.blue(), 255));

    auto blit = [&](int cell, const unsigned char* g) {
        for (int row = 0; row < 8; ++row) {
            QRgb* line = reinterpret_cast<QRgb*>(img.scanLine(row + GLYPH_Y));
            for (int col = 0; col < 8; ++col)
                if (g[row] & (1u << col)) line[cell * CELL_W + col] = on;
        }
    };
    for (int i = 0; i < COUNT; ++i) blit(i, FONT8x8[i]);
    blit(COUNT, GLYPH_COPY);

    return *m_atlas.insert(key, img);
}

void PixelFont::draw(QPainter& p, const QString& textIn, int x, int y,
                     const QColor& color, int scale, int scaleY, bool retro) {
    if (scale < 1) scale = 1;
    if (scaleY < 1) scaleY = 1;
    const QString text = sanitize(textIn);
    const QImage& a = atlas(color);

    const int dw = CELL_W * scale;
    const int dh = CELL_H * scale * scaleY;

    // 8x8 표에 없는 글자(한글 등)는 시스템 폰트로 대신 그린다.
    //   이 프로그램은 로그와 메뉴가 한국어라, 없는 글자를 그냥 버리면
    //   문장이 통째로 사라진다. 대신 칸 격자는 지키려고 전각 글자는
    //   두 칸을 차지하게 한다.
    //   한글은 8x8 라틴 글자보다 획이 많아 셀 높이 그대로는 뭉개지므로 조금 크게 그린다.
    //   글자 크기는 두 칸 폭(dw*2)을 넘지 않게, 높이는 줄 간격 안에서 정한다.
    //   (줄 간격에 여유가 있어 위아래로 조금 넘쳐도 다른 줄을 침범하지 않는다)
    //   내장 폰트는 셀 배율(scale) 그대로 정수 배로 키운다 (영문 8x8 글자와 같은 배율).
    const int px = !bundledFamily().isEmpty() ? BUNDLED_PX * scale
                                              : qMax(12, qMin(int(dh * 1.4), int(dw * 2 * 0.95)));

    auto cellOf = [](ushort u) -> int {
        if (u == 0x00A9)                          return COUNT;
        if (u >= FIRST && u < FIRST + COUNT)      return u - FIRST;
        return -1;
    };

    int col = 0, i = 0;
    while (i < text.size()) {
        const int cell = (m_unified && !retro) ? -1 : cellOf(text.at(i).unicode());
        if (cell >= 0) {
            // 확대는 최근접 보간이어야 픽셀이 뭉개지지 않는다 (기본값이 그렇다)
            p.drawImage(QRect(x + col * dw, y, dw, dh), a,
                        QRect(cell * CELL_W, 0, CELL_W, CELL_H));
            ++col; ++i;
            continue;
        }
        // 표에 없는 글자는 한 글자씩 자기 칸 안에 그린다.
        //   전각(한글 등)은 두 칸, 그 밖은 한 칸을 차지해 cells()/width() 가 계산한 폭과
        //   실제로 그려지는 폭이 항상 같다. (그래야 가운데 정렬과 말줄임이 어긋나지 않는다)
        //   폭이 일정하게 유지되도록 글자를 슬롯 가운데에 놓는다.
        const ushort u = text.at(i).unicode();
        const int nslot = unitCells(text.at(i));
        if (u > 0x20) {
            const KoRun& k = koreanRun(QString(text.at(i)), color, px);
            const int slotW = nslot * dw;
            const int ox = (slotW - k.advance) / 2;
            // 이미지 안의 몸통 중앙이 셀 세로 중앙(y + dh/2)에 오게 놓는다
            p.drawImage(x + col * dw + ox - k.pad, y + dh / 2 - k.baselineY, k.img);
        }
        col += nslot;
        ++i;
    }
}

