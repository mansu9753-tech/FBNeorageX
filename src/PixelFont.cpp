// 상태줄의 "NeoRAGE (c) 1999" 에 쓰는 저작권 기호. 위 표에는 없어서 직접 넣는다.
const unsigned char GLYPH_COPY[8] =
    { 0x7E, 0x81, 0x9D, 0x85, 0x85, 0x9D, 0x81, 0x7E };

// 한글에 쓸 글자체. 8x8 라틴 글자와 분위기가 가장 가까운 것(각지고 획이 굵은 도트풍)부터
//   찾고, 없으면 흔한 고딕으로 내려간다. 설치되어 있는 첫 번째를 쓴다.
// 프로그램에 내장한 도트 한글 폰트(GalmuriMono11, SIL OFL 1.1 — assets/fonts/LICENSE-Galmuri.txt).
//   등폭이라 영문 한 글자가 6px, 한글이 12px(영문의 두 배)로 셀 격자(1칸/2칸)에 그대로 맞는다.
//   영문도 이 폰트로 그리면 한글과 크기가 같다. 12px 로 그리고 정수 배로만 키운다.
constexpr int BUNDLED_PX = 12;

QString bundledFamily() {
    static const QString fam = [] {
        const int id = QFontDatabase::addApplicationFont(QStringLiteral(":/assets/fonts/GalmuriMono11.ttf"));
        if (id < 0) return QString();
        const QStringList fs = QFontDatabase::applicationFontFamilies(id);
        if (fs.isEmpty()) return QString();
        // 한글 글리프가 실제로 들어 있는지 확인한다 (못 그리면 대체 글자체로 내려간다)
        QFont probe(fs.first()); probe.setPixelSize(BUNDLED_PX);
        return QFontMetrics(probe).inFontUcs4(0xD55C) ? fs.first() : QString();
    }();
    return fam;
}

// 내장 폰트가 안 읽힐 때만 쓰는 대체 글자체. 설치되어 있는 첫 번째를 쓴다.
QString koreanFamily() {
    static const QString chosen = [] {
        static const char* prefer[] = {
            "Galmuri11", "Galmuri9", "NeoDunggeunmo", "DungGeunMo", "Dotum", "Gulim",
            "Malgun Gothic", "Noto Sans Mono CJK KR", "Noto Sans CJK KR", "NanumGothic",
            "NanumBarunGothic", "Droid Sans Fallback", "Unifont"
        };
        const QStringList fams = QFontDatabase::families();      // 같은 목록의 begin/end 를 써야 한다
        const QSet<QString> have(fams.begin(), fams.end());
        for (const char* f : prefer)
            if (have.contains(QString::fromUtf8(f))) return QString::fromUtf8(f);
        return QString();      // 못 찾으면 앱 기본 폰트가 알아서 대체 글꼴을 고른다
    }();
    return chosen;
}

